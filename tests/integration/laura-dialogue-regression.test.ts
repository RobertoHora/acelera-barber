import {it,expect,vi,afterEach} from 'vitest';
import {consultativeReply} from '../../services/laura-engine/consultative-cognition';
import {prisma} from '@/lib/db';
afterEach(()=>{vi.unstubAllEnvs();vi.unstubAllGlobals();});
it('uses history and excludes URLs generated by the model',async()=>{
 const b=await prisma.business.findFirstOrThrow();
 vi.stubEnv('LAURA_OPENROUTER_API_KEY','fixture-key');
 const fetchMock=vi.fn().mockResolvedValue({ok:true,json:async()=>({choices:[{message:{content:JSON.stringify({replyParts:['claro, a análise mostra sugestões de ajustes. https://wrong.example'],consent:true,deliverLink:true})}}]})});vi.stubGlobal('fetch',fetchMock);
 const reply=await consultativeReply('Ainda não entendi, mas pode enviar.','+5511988880999',b.id);
 expect(reply?.replyText).not.toContain('https://');expect(reply?.consent).toBe(true);
 const payload=JSON.parse(fetchMock.mock.calls[0][1].body);expect(payload.model).toBe('anthropic/claude-haiku-4.5');expect(payload.messages.at(-1).content).toContain('Ainda não entendi');
 expect(payload.messages[0].content).toContain('Responda a dúvida atual antes de avançar');
});
